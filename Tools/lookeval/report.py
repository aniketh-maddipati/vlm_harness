"""Numbers-only report from the PST50 look eval's evidence (pst50.py's JSON) → Tools/lookeval/report/pst50.{md,json}.
  python -I -W ignore Tools/lookeval/report.py [out dir]
"""
import os, sys, json, glob, csv
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lookmath as lm
import fit as F
from colour import D

EV = os.environ.get('LUMINA_LOOKEVAL', os.path.expanduser('~/LuminaEvidence/lookeval'))
OUTD = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'report')


def med(xs):
    return round(float(np.median(xs)), 2)


def main():
    P = {r['id']: r for r in (json.load(open(f)) for f in glob.glob(f'{EV}/pairs/pair_*.json'))}
    ids = sorted(P)
    ref = {int(r['id']): r for r in csv.DictReader(open(f'{D}per_pair.csv'))}
    S, md = {'n_pairs': len(ids)}, []
    w = md.append
    w('# PST50: Skim\'s look sliders against a professional grade\n')
    w(f'Generated by `Tools/lookeval/report.py` from `{EV.replace(os.path.expanduser("~"), "~")}`. Numbers only; no frames.')
    w('ΔE2000 on held-out 32 px blocks at 960×540, Skim\'s own maths (`lookmath.py` = the page\'s LOOK block, parity 1e-15) '
      'with the slider values as the page stores them. Per pair: median and p95 over pixels; table: median over pairs.\n')

    # ---- 1. how close
    rows = [('technical Rec.709 (content_709 as is)', [P[i]['tech709'] for i in ids]),
            ('A · global sliders (Light + Color, 10)', [P[i]['A']['global']['held'] for i in ids]),
            ('A · global + Mix (34)', [P[i]['A']['mix']['held'] for i in ids]),
            ('A · global + Grade (24)', [P[i]['A']['grade']['held'] for i in ids]),
            ('A · every slider (48)', [P[i]['A']['full']['held'] for i in ids]),
            ('B · global sliders, log read as S-Log3', [P[i]['B']['global']['held'] for i in ids]),
            ('B · every slider, log read as S-Log3', [P[i]['B']['full']['held'] for i in ids]),
            ('B · rest (S-Log3 table alone)', [P[i]['B']['rest'] for i in ids]),
            ('curves + 3×3, log → GT (PST50 note)', [(float(ref[i]['curves_med']), float(ref[i]['curves_p95'])) for i in ids]),
            ('33³ LUT, log → GT (the floor)', [(float(ref[i]['lut33_med']), float(ref[i]['lut33_p95'])) for i in ids])]
    w('## 1. How much of the grade the sliders reproduce (one pair = one frame, fitted and scored on it)\n')
    w('| model | ΔE median | ΔE p95 | pairs with median < 1 / < 2 / < 3 | worst pair (median) |')
    w('|---|---|---|---|---|')
    S['models'] = {}
    for name, v in rows:
        a = np.array(v)
        worst = ids[int(np.argmax(a[:, 0]))]
        w(f'| {name} | {med(a[:, 0])} | {med(a[:, 1])} | {(a[:, 0] < 1).sum()} / {(a[:, 0] < 2).sum()} / {(a[:, 0] < 3).sum()} | {a[:, 0].max():.2f} (id {worst}) |')
        S['models'][name] = {'median': med(a[:, 0]), 'p95': med(a[:, 1]), 'lt1': int((a[:, 0] < 1).sum()), 'lt2': int((a[:, 0] < 2).sum()), 'lt3': int((a[:, 0] < 3).sum())}
    gap = [P[i]['A']['full']['held'][0] - P[i]['A']['full']['fit'][0] for i in ids]
    w(f'\nFit blocks vs held-out blocks (A, every slider): median gap {med(gap)} ΔE, so 48 sliders do not overfit one frame.')
    w('Inputs: **A** = `content_709` in mode 0 (as shot): assumes the clip reaches Skim already in Rec.709 through the same '
      'technical conversion PST50 used. **B** = `content_log` in mode 1: assumes the unnamed log curve is S-Log3 (it is not '
      'for most frames; see the rest row), so B is the price of a wrong log assumption plus what the sliders recover.\n')

    # ---- 2. which sliders
    w('## 2. Which sliders carry the gain (A)\n')
    w('From the every-slider fit (median over pairs, ΔE median). **drop** = refit everything else without the group; '
      '**zero** = put the group back at rest in the fitted look, no refit; **only** = fit the group alone from rest.\n')
    full = med([P[i]['A']['full']['held'][0] for i in ids])
    w(f'| group | sliders | drop (Δ vs all {full}) | zero (Δ) | only (ΔE) |')
    w('|---|---|---|---|---|')
    S['groups'] = {}
    for g, ps in F.GROUPS.items():
        dr = med([P[i]['A']['drop'][g][0] - P[i]['A']['full']['held'][0] for i in ids])
        ze = med([P[i]['A']['zero'][g][0] - P[i]['A']['full']['held'][0] for i in ids])
        on = med([P[i]['A']['only'][g][0] for i in ids])
        w(f'| {g} | {len(ps)} | {dr:+.2f} | {ze:+.2f} | {on} |')
        S['groups'][g] = {'drop_delta': dr, 'zero_delta': ze, 'only': on}
    # sliders at their limits
    w('\nSliders pinned at a range limit in the fitted looks (share of pairs; the grade asks for more than the slider has):\n')
    w('| slider | global fit | every-slider fit |')
    w('|---|---|---|')
    S['pinned'] = {}
    for p in [p for p, _ in lm.ROWS_LIGHT + lm.ROWS_COLOR] + ['grade.sh.s', 'grade.mid.s', 'grade.hi.s', 'grade.all.s']:
        a, b = lm.rng(p)
        sh = []
        for st in ('global', 'full'):
            vs = [P[i]['A'][st]['look'].get(p, lm.default(p)) for i in ids]
            sh.append(np.mean([(v <= a or v >= b) and v != lm.default(p) for v in vs]))
        if max(sh) > 0:
            w(f'| {p} | {sh[0]:.0%} | {sh[1]:.0%} |')
            S['pinned'][p] = [round(float(x), 2) for x in sh]
    w('\nMedian |value| of each Light / Color slider in the every-slider fit: ' + ', '.join(
        f'{p} {np.median([abs(P[i]["A"]["full"]["look"].get(p, 0)) for i in ids]):.{2 if p == "ev" else 0}f}'
        for p, _ in lm.ROWS_LIGHT + lm.ROWS_COLOR) + '.\n')

    # ---- 3. transfer
    T = json.load(open(f'{EV}/transfer.json')) if os.path.exists(f'{EV}/transfer.json') else None
    w('## 3. Transfer: fitted on one frame, applied to another shot of the same look\n')
    w('PST50 has **no graded clip frames**: one graded frame per content shot. Two proxies:\n')
    if T:
        w('**(a) Style-source clips** (29, 37, 46): the clip\'s matching frame graded is `tarN`, the content frame graded is '
          '`gtN`, one look on two shots. Fit on one, apply to the other. Mode A puts the clip frame through the content '
          'frame\'s own log → 709 conversion (a LUT fitted content_log → content_709). Clip 46 is Rec.709, not log, so its '
          'input range does not overlap the content frame\'s.\n')
        w('| clip | own fit (content / clip) | content → clip | clip → content | LUT content → clip / clip → content | 709 vs tar |')
        w('|---|---|---|---|---|---|')
        S['clips'] = T['clips']
        for c in T['clips']:
            for key in ('A', 'B'):
                r = c[key]
                f = lambda t: f'{t[0]:.2f} / {t[1]:.2f}'
                lut = f"{c['lut709']['content_to_clip'][0]:.2f} / {c['lut709']['clip_to_content'][0]:.2f}" if key == 'A' else '—'
                w(f"| {c['id']} {key} | global {r['content_own']['global'][0]:.2f} / {r['clip_own']['global'][0]:.2f}, all "
                  f"{r['content_own']['full'][0]:.2f} / {r['clip_own']['full'][0]:.2f} | global {f(r['content_to_clip']['global'])}, all {f(r['content_to_clip']['full'])} | "
                  f"global {f(r['clip_to_content']['global'])}, all {f(r['clip_to_content']['full'])} | {lut} | {c['clip_tech709_vs_tar'][0]:.2f} |")
        w('\n(cells: ΔE median / p95 unless one number; "all" = every slider.)\n')
        w('**(b) Look clusters** (PST50 pairs whose LUTs cross at ΔE < 3: {2,21}, {44,46}, {4,39}, {30,36}): pair a\'s look applied to pair b.\n')
        w('| from → to | global | every slider | 33³ LUT (709 → GT) | own fit of b (global / all) | 709 vs GT |')
        w('|---|---|---|---|---|---|')
        S['clusters'] = T['clusters']
        for c in T['clusters']:
            w(f"| {c['from']} → {c['to']} | {c['global'][0]:.2f} / {c['global'][1]:.2f} | {c['full'][0]:.2f} / {c['full'][1]:.2f} | "
              f"{c['lut709'][0]:.2f} / {c['lut709'][1]:.2f} | {c['global_own'][0]:.2f} / {c['full_own'][0]:.2f} | {c['tech709'][0]:.2f} |")
    X = {}
    for f in glob.glob(f'{EV}/cross/from_*.json'):
        X[int(os.path.basename(f)[5:-5])] = json.load(open(f))
    if len(X) == len(ids):
        w('\n**(c) Any other look** (each pair\'s fitted look on all 49 others, 20k held-out pixels, ΔE median):\n')
        cr = np.load(f'{D}cross_lut_median_dE.npy')
        S['cross'] = {}
        for st in ('global', 'full'):
            off = [X[s][st][str(t)] for s in ids for t in ids if s != t]
            S['cross'][st] = med(off)
            w(f'- {st} sliders: median {med(off)}, {np.mean(np.array(off) < 3):.0%} of 2450 under 3')
        w(f'- 33³ LUT (PST50 note): median {med(cr[~np.eye(50, dtype=bool)])}; technical 709: {S["models"]["technical Rec.709 (content_709 as is)"]["median"]}')
    os.makedirs(OUTD, exist_ok=True)
    open(f'{OUTD}/pst50.md', 'w').write('\n'.join(md) + '\n')
    json.dump(S, open(f'{OUTD}/pst50.json', 'w'), indent=1)
    print('\n'.join(md))


if __name__ == '__main__':
    main()
